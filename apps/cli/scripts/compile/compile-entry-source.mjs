/**
 * Source text of the generated `compile-entry.ts` (PRD-0038).
 *
 * Extracted from build.mjs so the exact string that becomes a shipped binary's
 * entry point is unit-testable. Two regressions this file exists to catch, both
 * of which broke `--profile=release` or `--profile=bytecode` at compile time
 * rather than at test time:
 *
 *  - globalThis writes must use computed property access. `(x as T)NAME` is a
 *    syntax error, so interpolating a bare global name silently produced an
 *    entry that bun's parser rejects — the release build failed for every
 *    artifact carrying SPA assets.
 *  - no top-level `await`. `--bytecode` cannot compile one, so boot goes through
 *    an async function.
 *
 * The generated file is TypeScript; the assertions in the matching test parse it
 * as text rather than evaluating it, because importing it would require the
 * staged `.node` addon and the SPA asset graph.
 */

export const CATALOG_GLOBAL_NAME = '__BYF_COMPILE_CATALOG__';

function assignToGlobal(name, value) {
  return `(globalThis as Record<string, unknown>)[${JSON.stringify(name)}] = ${value};`;
}

/**
 * @param {{
 *   clipboardRelativeRequire: string,
 *   mainEntryPath: string,
 *   catalogInjectPath: string,
 *   assetSets: ReadonlyArray<{ entryPath: string | null, globalName: string }>,
 * }} input
 */
export function buildCompileEntrySource({
  clipboardRelativeRequire,
  mainEntryPath,
  catalogInjectPath,
  assetSets,
}) {
  const importBlocks = [];
  const assignBlocks = [];
  assetSets.forEach((set, i) => {
    if (set.entryPath === null) return;
    const ident = `embeddedAssets_${i}`;
    importBlocks.push(
      `import { embeddedAssets as ${ident} } from ${JSON.stringify(set.entryPath)};`,
    );
    assignBlocks.push(assignToGlobal(set.globalName, ident));
  });
  const assetsImport = importBlocks.length > 0 ? `\n${importBlocks.join('\n')}` : '';
  const assetsAssign = assignBlocks.length > 0 ? `\n${assignBlocks.join('\n')}` : '';

  return `/**
 * AUTO-GENERATED by scripts/compile/build.mjs — do not edit.
 * Embeds the platform clipboard N-API addon and boots src/main.ts.
 */
import { createRequire } from 'node:module';
import catalogJson from ${JSON.stringify(catalogInjectPath)};${assetsImport}
// Embed .node into the standalone binary (path becomes /$bunfs/root/... after compile).
import clipboardNodePath from ${JSON.stringify(clipboardRelativeRequire)} with { type: "file" };

const require = createRequire(import.meta.url);

// napi-rs host package (@mariozechner/clipboard) checks this env first.
process.env.NAPI_RS_NATIVE_LIBRARY_PATH = clipboardNodePath;
// Fail fast if the embedded binding cannot load (do not wait for TUI clipboard use).
require(clipboardNodePath);

if (typeof catalogJson === 'string' && catalogJson.length > 0) {
  ${assignToGlobal(CATALOG_GLOBAL_NAME, 'catalogJson')}
}${assetsAssign}

// The '--bytecode' flag cannot compile a top-level await (bun 1.3.14), so the
// boot is wrapped in an async function. main.ts only auto-starts when
// import.meta.main is true — false when imported as a dependency — hence the
// explicit call. Boot ordering is unchanged: the dynamic import still runs
// after every globalThis assignment above.
async function boot() {
  const { main } = await import(${JSON.stringify(mainEntryPath)});
  main();
}
void boot();
`;
}
